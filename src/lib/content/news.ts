export function newsForToday(date = new Date()): NewsItem[] {
  const offset = (date.getFullYear() * 400 + date.getMonth() * 31 + date.getDate()) % NEWS.length;
  return [...NEWS.slice(offset), ...NEWS.slice(0, offset)];
}
